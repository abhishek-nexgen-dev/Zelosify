-- Restructure Role enum type to ADMIN, RECRUITER, HIRING_MANAGER, CANDIDATE
CREATE TYPE "Role_new" AS ENUM ('ADMIN', 'RECRUITER', 'HIRING_MANAGER', 'CANDIDATE');

ALTER TABLE "User" ALTER COLUMN "role" TYPE "Role_new" USING (
  CASE
    WHEN "role"::text IN ('BUSINESS_APPROVER', 'BUSINESS_USER', 'FINANCE_MANAGER', 'PROCUREMENT_MANAGER', 'RESOURCE_MANAGER', 'VENDOR_MANAGER') THEN 'RECRUITER'::"Role_new"
    WHEN "role"::text = 'IT_VENDOR' THEN 'CANDIDATE'::"Role_new"
    WHEN "role"::text IN ('ADMIN', 'RECRUITER', 'HIRING_MANAGER', 'CANDIDATE') THEN "role"::text::"Role_new"
    ELSE 'CANDIDATE'::"Role_new"
  END
);

DROP TYPE "Role";
ALTER TYPE "Role_new" RENAME TO "Role";
